#!/bin/sh
#
# Fixture-only, manual, non-publishing rehearsal of the Go -> Rust self-hosted cutover.
#
# This is a SYNTHETIC rehearsal, not a production cutover and not evidence for real
# volumes. It exists to exercise, in one deterministic run, the operator sequence:
#   1. build the reference Go image (`deploy/container/Containerfile`) and the
#      experimental, non-publishing Rust image (`deploy/container/Containerfile.rust`);
#   2. run the Go runtime against a synthetic, read-only library to generate a real
#      Go v8 database (schema + admin + catalog), then STOP the Go writer (quiesce)
#      before the database is taken as importer input;
#   3. import that database with `learnvault-server migrate-go --input/--backup/--output
#      --library-id`, verify the report, the unchanged source checksum and that the
#      output and backup exist and are distinct;
#   4. start the hardened experimental Rust OCI against ONLY the imported Rust output,
#      staged as `/data/learnvault.sqlite`, plus the same synthetic `/library:ro`, and
#      assert health, 401, authentication, catalog (with the known synthetic lesson),
#      range media, study persistence, nonroot/no caps/read-only, restart persistence
#      and cleanup;
#   5. exercise a fail-closed negative path that proves no Rust output is promoted.
#
# Safety invariants:
#   - Builds and runs only against `mktemp` synthetic fixtures; never reads the real
#     library or user data (the guard refuses anything outside the temp tree). Unsafe
#     TMPDIR/TEMP/TMP values (under /mnt or a cursos tree) are dropped before `mktemp`.
#   - Go and Rust data directories are distinct and the run hard-fails if they resolve
#     identically; neither runtime is ever mounted against the other's data directory.
#   - The Go v8 database is generated by running the Go runtime, never constructed or
#     shipped as a binary.
#   - Credentials are fixed synthetic values, not caller-configurable: if ADMIN_USERNAME
#     or ADMIN_PASSWORD is already set in the environment the rehearsal fails closed.
#     They exist only in temp/container environment and are never printed (no shell
#     tracing, no echo/printf of the password).
#   - Nothing is published or pushed: this is not a release step.
#
# Requirements:
#   - Docker or Podman on PATH (override with `CONTAINER_ENGINE`, e.g. `podman`);
#   - network access for the Go/Rust/Node dependency downloads during both builds.
#
# Usage:
#   ./scripts/verify-go-to-rust-cutover.sh
#   CONTAINER_ENGINE=podman ./scripts/verify-go-to-rust-cutover.sh
#   KEEP=1 ./scripts/verify-go-to-rust-cutover.sh   # keep the temp fixture for debugging
#
set -eu

# Git Bash/MSYS rewrites absolute POSIX arguments (for example `/library` or
# `/data/learnvault.sqlite`) into Windows paths before `docker.exe` receives them,
# which corrupts container-side paths. Disabling that keeps container paths literal.
# The variable is ignored on Linux/macOS.
MSYS_NO_PATHCONV=1
export MSYS_NO_PATHCONV

GO_IMAGE="${GO_IMAGE:-learnvault-go-cutover-rehearsal:local}"
RUST_IMAGE="${RUST_IMAGE:-learnvault-rust-cutover-rehearsal:local}"
GO_CONTAINER="${GO_CONTAINER:-learnvault-go-cutover-rehearsal}"
RUST_CONTAINER="${RUST_CONTAINER:-learnvault-rust-cutover-rehearsal}"
GO_PORT="${GO_PORT:-8091}"
RUST_PORT="${RUST_PORT:-8092}"
KEEP="${KEEP:-0}"
LIBRARY_ID="library-1"
# The path of the known synthetic lesson inside the library, relative to its root.
LESSON_PATH="synthetic/course-1/module-1/lesson-1/lesson.mp4"

# Synthetic credentials are fixed, not configurable. A caller-supplied ADMIN_USERNAME or
# ADMIN_PASSWORD could carry a real secret into the process environment and the container
# `-e` arguments, so refuse them and fail closed before anything runs.
if [ -n "${ADMIN_USERNAME:-}" ] || [ -n "${ADMIN_PASSWORD:-}" ]; then
	printf '%s\n' 'ERROR: refusing caller-supplied ADMIN_USERNAME/ADMIN_PASSWORD.' >&2
	printf '%s\n' 'This rehearsal uses fixed synthetic credentials only; unset both variables.' >&2
	exit 2
fi
ADMIN_USERNAME="admin"
ADMIN_PASSWORD="learnvault-rehearsal-pass"

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_root=$(CDPATH= cd -- "$script_dir/.." && pwd)

# Translate POSIX paths to the host syntax the container engine expects when running
# under an MSYS/Cygwin shell (for example Git Bash on Windows).
host_path() {
	if command -v cygpath >/dev/null 2>&1; then
		cygpath -w -- "$1"
	else
		printf '%s' "$1"
	fi
}

engine="${CONTAINER_ENGINE:-}"
if [ -z "$engine" ]; then
	if command -v docker >/dev/null 2>&1; then
		engine=docker
	elif command -v podman >/dev/null 2>&1; then
		engine=podman
	else
		printf '%s\n' 'ERROR: this rehearsal requires Docker or Podman.' >&2
		printf '%s\n' 'Install one, or set CONTAINER_ENGINE to the engine binary.' >&2
		exit 2
	fi
elif ! command -v "$engine" >/dev/null 2>&1; then
	printf 'ERROR: CONTAINER_ENGINE=%s was not found on PATH.\n' "$engine" >&2
	exit 2
fi

printf 'Using container engine: %s\n' "$engine"

# Temporary-root preflight, run BEFORE the first filesystem mutation. `mktemp -d` honors
# TMPDIR/TEMP/TMP, so a hostile or mistaken caller could otherwise force the fixture to be
# created under /mnt or a cursos tree. Any such value is refused and dropped here so `mktemp`
# falls back to the safe default (/tmp on POSIX and on MSYS/Git Bash), which keeps
# Windows/MSYS support. No external tool is used, so the check is always effective.
#
# The check resolves symlinks: a lexical match alone misses an alias such as
# TMPDIR=/tmp/to-cursos where `to-cursos` -> the real-data tree, which would let
# `mktemp -d` create the fixture inside real user data before any later guard could see it.
is_unsafe_temp_root() {
	case "$1" in
	/mnt | /mnt/* | */cursos | */cursos/*) return 0 ;;
	*) return 1 ;;
	esac
}

# Canonical (symlink-resolving) form of a path using only the shell; on any failure
# (missing path, `cd` refused) it falls back to the literal input so callers always get a
# usable value.
real_path() {
	(CDPATH= cd -- "$1" 2>/dev/null && pwd -P) || printf '%s' "$1"
}

drop_unsafe_temp_root() {
	temp_name=$1
	temp_value=$2
	if [ -z "$temp_value" ]; then
		return 0
	fi
	temp_resolved=$(real_path "$temp_value")
	if is_unsafe_temp_root "$temp_value" || is_unsafe_temp_root "$temp_resolved"; then
		printf 'WARNING: refusing unsafe %s=%s; fixtures will not be created there.\n' \
			"$temp_name" "$temp_value" >&2
		unset "$temp_name"
	fi
}

sanitize_temp_environment() {
	drop_unsafe_temp_root TMPDIR "${TMPDIR:-}"
	drop_unsafe_temp_root TEMP "${TEMP:-}"
	drop_unsafe_temp_root TMP "${TMP:-}"
}
sanitize_temp_environment

workdir=$(mktemp -d)
library="$workdir/library"
go_data="$workdir/go-data"
rust_input="$workdir/rust-input"
rust_output_dir="$workdir/rust-output"
rust_backup_dir="$workdir/rust-backup"
rust_data="$workdir/rust-run-data"
rust_output="$rust_output_dir/learnvault.sqlite"
rust_backup="$rust_backup_dir/go.sqlite.backup"
go_db="$go_data/learnvault.sqlite"

go_started=0
rust_started=0

cleanup() {
	status=$?
	trap - EXIT INT TERM
	if [ "$go_started" = 1 ]; then
		"$engine" rm -f "$GO_CONTAINER" >/dev/null 2>&1 || true
	fi
	if [ "$rust_started" = 1 ]; then
		"$engine" rm -f "$RUST_CONTAINER" >/dev/null 2>&1 || true
	fi
	if [ "$KEEP" = 1 ]; then
		printf 'Kept temporary fixture at %s (KEEP=1)\n' "$workdir"
	else
		rm -rf "$workdir"
	fi
	exit "$status"
}
trap cleanup EXIT INT TERM

# Refuse real-data paths: everything this rehearsal touches must live under the temp
# fixture tree, and the real library/data tree is never accepted. This is belt and
# braces because the script only ever builds these paths itself.
guard_fixture_path() {
	path=$1
	case "$path" in
	/mnt/* | /mnt | */cursos | */cursos/*)
		printf 'ERROR: refusing real-data path: %s\n' "$path" >&2
		printf '%s\n' 'This rehearsal only accepts synthetic fixtures under its mktemp directory.' >&2
		exit 3
		;;
	esac
	# Defense in depth: also refuse a real-data tree reached through a symlink alias,
	# which the lexical check above cannot see.
	resolved_path=$(real_path "$path")
	case "$resolved_path" in
	/mnt/* | /mnt | */cursos | */cursos/*)
		printf 'ERROR: refusing real-data path (resolved): %s -> %s\n' "$path" "$resolved_path" >&2
		printf '%s\n' 'This rehearsal only accepts synthetic fixtures under its mktemp directory.' >&2
		exit 3
		;;
	esac
	case "$path" in
	"$workdir" | "$workdir"/*) ;;
	*)
		printf 'ERROR: fixture path escapes the temporary directory: %s\n' "$path" >&2
		exit 3
		;;
	esac
}

resolve_dir() {
	real_path "$1"
}

checksum() {
	if command -v sha256sum >/dev/null 2>&1; then
		sha256sum -- "$1" | awk '{print $1}'
	elif command -v shasum >/dev/null 2>&1; then
		shasum -a 256 "$1" | awk '{print $1}'
	elif command -v cksum >/dev/null 2>&1; then
		cksum <"$1"
	else
		printf '%s\n' 'ERROR: no checksum tool (sha256sum, shasum or cksum) is available.' >&2
		exit 4
	fi
}

# Belt-and-braces: the created temp root itself must pass the fixture guard before any
# child directory is created under it.
guard_fixture_path "$workdir"

mkdir -p "$library/synthetic/course-1/module-1/lesson-1"
mkdir -p "$go_data" "$rust_input" "$rust_output_dir" "$rust_backup_dir" "$rust_data"

guard_fixture_path "$library"
guard_fixture_path "$go_data"
guard_fixture_path "$rust_data"

# Hard fail if the Go and Rust data directories ever resolve to the same location:
# mounting both runtimes against one data volume would corrupt the rehearsal.
resolved_go_data=$(resolve_dir "$go_data")
resolved_rust_data=$(resolve_dir "$rust_data")
if [ "$resolved_go_data" = "$resolved_rust_data" ]; then
	printf '%s\n' 'ERROR: Go and Rust data directories resolve identically; refusing to run.' >&2
	exit 3
fi

# Synthetic fixture: tiny deterministic bytes, never real course media. The 64 KiB
# media file gives the range request something to slice.
head -c 65536 /dev/zero >"$library/synthetic/course-1/module-1/lesson-1/lesson.mp4"
printf '%s\n' '1' >"$library/synthetic/course-1/module-1/lesson-1/lesson.srt"
chmod -R a+rX "$library" 2>/dev/null || true
# Both runtimes run as uid 10001: data and importer destination directories must be
# writable, while the library stays readable only.
chmod 0755 "$workdir" 2>/dev/null || true
chmod 0777 "$go_data" "$rust_output_dir" "$rust_backup_dir" "$rust_data" 2>/dev/null || true
chmod 0755 "$rust_input" 2>/dev/null || true

printf 'Building %s (reference Go runtime) ...\n' "$GO_IMAGE"
"$engine" build \
	-f "$(host_path "$repo_root/deploy/container/Containerfile")" \
	-t "$GO_IMAGE" \
	"$(host_path "$repo_root")"

printf 'Building %s (experimental Rust runtime) ...\n' "$RUST_IMAGE"
"$engine" build \
	-f "$(host_path "$repo_root/deploy/container/Containerfile.rust")" \
	-t "$RUST_IMAGE" \
	"$(host_path "$repo_root")"

failures=0
pass() { printf 'PASS: %s\n' "$1"; }
fail() {
	printf 'FAIL: %s\n' "$1" >&2
	failures=$((failures + 1))
}
skip() { printf 'SKIP: %s\n' "$1"; }

library_mount="$(host_path "$library"):/library:ro"
go_data_mount="$(host_path "$go_data"):/data:rw"
rust_data_mount="$(host_path "$rust_data"):/data:rw"

printf '\nStarting the Go runtime to generate a v8 database ...\n'
"$engine" run -d --name "$GO_CONTAINER" \
	--read-only \
	--tmpfs "/tmp:rw,noexec,nosuid,size=16m" \
	--security-opt no-new-privileges \
	--cap-drop ALL \
	-e "LISTEN_ADDR=0.0.0.0" \
	-e "PORT=$GO_PORT" \
	-e "DATA_DIR=/data" \
	-e "CACHE_DIR=/tmp/cache" \
	-e "LIBRARY_DIR=/library" \
	-e "COOKIE_SECURE=false" \
	-e "ADMIN_USERNAME=$ADMIN_USERNAME" \
	-e "ADMIN_PASSWORD=$ADMIN_PASSWORD" \
	-v "$library_mount" \
	-v "$go_data_mount" \
	"$GO_IMAGE" \
	>/dev/null
go_started=1

printf 'Waiting for the Go /api/healthz (up to 30s) ...\n'
go_health=0
attempt=0
while [ "$attempt" -lt 30 ]; do
	if "$engine" exec "$GO_CONTAINER" wget -q -O /dev/null \
		"http://127.0.0.1:$GO_PORT/api/healthz" >/dev/null 2>&1; then
		go_health=1
		break
	fi
	attempt=$((attempt + 1))
	sleep 1
done
if [ "$go_health" = 1 ]; then
	pass 'Go runtime answers /api/healthz'
else
	fail 'Go runtime did not answer /api/healthz within 30s'
	"$engine" logs "$GO_CONTAINER" 2>&1 | tail -n 20 || true
fi

# Authenticate to the Go service (synthetic credentials, never printed) and catalog the
# read-only synthetic library so the generated database carries real catalog rows.
go_login=$("$engine" exec "$GO_CONTAINER" wget -q -S -O - \
	--header "Origin: http://127.0.0.1:$GO_PORT" \
	--header "Content-Type: application/json" \
	--post-data "{\"username\":\"$ADMIN_USERNAME\",\"password\":\"$ADMIN_PASSWORD\"}" \
	"http://127.0.0.1:$GO_PORT/api/login" 2>&1 || true)
go_token=$(printf '%s\n' "$go_login" | sed -n 's/.*[Ss]et-[Cc]ookie: learnvault_session=\([^;]*\).*/\1/p' | head -n 1)
if [ -n "$go_token" ]; then
	pass 'Go runtime authenticates the synthetic admin'
else
	fail 'Go runtime did not issue a session cookie'
fi

if [ -n "$go_token" ]; then
	"$engine" exec "$GO_CONTAINER" wget -q -O - \
		--header "Cookie: learnvault_session=$go_token" \
		--header "Origin: http://127.0.0.1:$GO_PORT" \
		--post-data "" \
		"http://127.0.0.1:$GO_PORT/api/admin/catalog/rescan" >"$workdir/go-rescan.json" 2>/dev/null || true
	if grep -q '"categories":1' "$workdir/go-rescan.json"; then
		pass 'Go runtime catalogued the synthetic read-only library'
	else
		fail "Go rescan did not catalogue the fixture: $(cat "$workdir/go-rescan.json" 2>/dev/null)"
	fi
fi

if "$engine" exec "$GO_CONTAINER" test -f /data/learnvault.sqlite; then
	pass 'Go runtime generated its v8 database'
else
	fail 'Go runtime did not create /data/learnvault.sqlite'
fi

printf '\nQuiescing the Go writer before taking its database ...\n'
"$engine" stop "$GO_CONTAINER" >/dev/null
go_started=0
if [ "$("$engine" inspect --format '{{.State.Running}}' "$GO_CONTAINER" 2>/dev/null || printf 'unknown')" = false ]; then
	pass 'Go writer is stopped (quiesced) before import'
else
	fail 'Go writer was not confirmed stopped before import'
fi

# Take the quiesced Go database (with any residual WAL/SHM companions) as importer input
# under the Rust fixture tree, then remove the Go container.
cp "$go_db" "$rust_input/go.sqlite"
if [ -f "$go_db-wal" ]; then cp "$go_db-wal" "$rust_input/go.sqlite-wal"; fi
if [ -f "$go_db-shm" ]; then cp "$go_db-shm" "$rust_input/go.sqlite-shm"; fi
"$engine" rm -f "$GO_CONTAINER" >/dev/null 2>&1 || true

input_mount="$(host_path "$rust_input"):/input:ro"
output_mount="$(host_path "$rust_output_dir"):/output:rw"
backup_mount="$(host_path "$rust_backup_dir"):/backup:rw"

input_checksum_before=$(checksum "$rust_input/go.sqlite")

printf '\nImporting the Go database into a Rust database ...\n'
set +e
migration_report=$("$engine" run --rm --entrypoint /app/learnvault-server \
	-v "$input_mount" \
	-v "$output_mount" \
	-v "$backup_mount" \
	"$RUST_IMAGE" migrate-go \
	--input /input/go.sqlite \
	--output /output/learnvault.sqlite \
	--backup /backup/go.sqlite.backup \
	--library-id "$LIBRARY_ID" 2>&1)
migration_status=$?
set -e

if [ "$migration_status" -eq 0 ]; then
	pass 'migrate-go completed successfully'
else
	fail "migrate-go failed (status $migration_status): $migration_report"
fi

if printf '%s' "$migration_report" | grep -q 'users='; then
	pass "importer report present ($migration_report)"
else
	fail "importer report missing (got: ${migration_report:-<empty>})"
fi

input_checksum_after=$(checksum "$rust_input/go.sqlite")
if [ "$input_checksum_before" = "$input_checksum_after" ]; then
	pass 'source Go database checksum is unchanged after import'
else
	fail "source Go database changed across import ($input_checksum_before -> $input_checksum_after)"
fi

if [ -f "$rust_output" ] && [ -f "$rust_backup" ]; then
	pass 'importer output and backup both exist'
else
	fail 'importer output and/or backup are missing'
fi

resolved_output=$(resolve_dir "$rust_output_dir")
resolved_backup=$(resolve_dir "$rust_backup_dir")
if [ "$resolved_output" != "$resolved_backup" ] && [ "$rust_output" != "$rust_backup" ]; then
	pass 'importer output and backup are distinct paths'
else
	fail 'importer output and backup are not distinct'
fi

# Negative path: a malformed CLI invocation (missing --library-id) must fail closed and
# promote no output. This proves the importer never leaves a partial artifact behind.
printf '\nNegative path (fail-closed): malformed migrate-go invocation ...\n'
set +e
negative_output=$("$engine" run --rm --entrypoint /app/learnvault-server \
	-v "$input_mount" \
	-v "$output_mount" \
	-v "$backup_mount" \
	"$RUST_IMAGE" migrate-go \
	--input /input/go.sqlite \
	--output /output/negative.sqlite \
	--backup /backup/negative.backup 2>&1)
negative_status=$?
set -e

if [ "$negative_status" -ne 0 ]; then
	pass "malformed migrate-go failed as expected (status $negative_status)"
else
	fail "malformed migrate-go unexpectedly succeeded: $negative_output"
fi

if [ ! -e "$rust_output_dir/negative.sqlite" ] && [ ! -e "$rust_backup_dir/negative.backup" ]; then
	pass 'negative path promoted no output (no output was promoted)'
else
	fail 'negative path left an output or backup behind'
fi

# Stage ONLY the promoted Rust output as the runtime database. This is a copy, so the
# importer output and backup are preserved and the runtime mutates only the staged copy.
cp "$rust_output" "$rust_data/learnvault.sqlite"
chmod 0666 "$rust_data/learnvault.sqlite" 2>/dev/null || true
if [ "$(checksum "$rust_data/learnvault.sqlite")" = "$(checksum "$rust_output")" ]; then
	pass 'Rust output staged as /data/learnvault.sqlite (identical bytes)'
else
	fail 'staged Rust database differs from the importer output'
fi

printf '\nStarting the hardened experimental Rust OCI ...\n'
"$engine" run -d --name "$RUST_CONTAINER" \
	--read-only \
	--tmpfs "/tmp:rw,noexec,nosuid,size=16m" \
	--security-opt no-new-privileges \
	--cap-drop ALL \
	-e "PORT=$RUST_PORT" \
	-e "COOKIE_SECURE=false" \
	-e "ADMIN_USERNAME=$ADMIN_USERNAME" \
	-e "ADMIN_PASSWORD=$ADMIN_PASSWORD" \
	-v "$library_mount" \
	-v "$rust_data_mount" \
	"$RUST_IMAGE" \
	--listen-addr "0.0.0.0:$RUST_PORT" \
	--database /data/learnvault.sqlite \
	--library-root /library \
	--insecure-http \
	>/dev/null
rust_started=1

printf 'Waiting for the Rust /api/healthz (up to 30s) ...\n'
rust_health=0
attempt=0
while [ "$attempt" -lt 30 ]; do
	if "$engine" exec "$RUST_CONTAINER" wget -q -O - \
		"http://127.0.0.1:$RUST_PORT/api/healthz" >"$workdir/rust-health.json" 2>/dev/null; then
		rust_health=1
		break
	fi
	attempt=$((attempt + 1))
	sleep 1
done

printf '\nChecks:\n'
if [ "$rust_health" != 1 ]; then
	fail 'Rust runtime did not answer /api/healthz within 30s'
	"$engine" logs "$RUST_CONTAINER" 2>&1 | tail -n 20 || true
else
	if grep -q '"status":"ok"' "$workdir/rust-health.json"; then
		pass 'GET /api/healthz returns {"status":"ok"}'
	else
		fail "unexpected /api/healthz payload: $(cat "$workdir/rust-health.json")"
	fi
fi

if "$engine" exec "$RUST_CONTAINER" wget -q -S -O /dev/null \
	"http://127.0.0.1:$RUST_PORT/api/catalog" 2>&1 | grep -q ' 401'; then
	pass '/api/catalog rejects unauthenticated requests (401)'
else
	fail '/api/catalog did not reject an unauthenticated request with 401'
fi

# Authenticate the migrated admin with the same synthetic credentials (fresh session
# over the migrated database), then read the migrated catalog.
rust_login=$("$engine" exec "$RUST_CONTAINER" wget -q -S -O - \
	--header "Origin: http://127.0.0.1:$RUST_PORT" \
	--header "Content-Type: application/json" \
	--post-data "{\"username\":\"$ADMIN_USERNAME\",\"password\":\"$ADMIN_PASSWORD\"}" \
	"http://127.0.0.1:$RUST_PORT/api/login" 2>&1 || true)
rust_token=$(printf '%s\n' "$rust_login" | sed -n 's/.*[Ss]et-[Cc]ookie: learnvault_session=\([^;]*\).*/\1/p' | head -n 1)
if [ -n "$rust_token" ]; then
	pass 'migrated admin authenticates with synthetic credentials'
else
	fail 'migrated admin could not authenticate against the imported database'
fi

rust_media_id=""
if [ -n "$rust_token" ]; then
	"$engine" exec "$RUST_CONTAINER" wget -q -O - \
		--header "Cookie: learnvault_session=$rust_token" \
		"http://127.0.0.1:$RUST_PORT/api/catalog" >"$workdir/rust-catalog.json" 2>/dev/null || true
	if grep -q "\"path\":\"$LESSON_PATH\"" "$workdir/rust-catalog.json"; then
		pass 'imported catalog contains the known synthetic lesson'
	else
		fail "imported catalog is missing $LESSON_PATH"
	fi
	rust_media_id=$(grep -oE "\"media_id\":\"[^\"]+\",\"name\":\"lesson\\.mp4\",\"path\":\"$LESSON_PATH\"" \
		"$workdir/rust-catalog.json" | head -n 1 | sed -E 's/.*"media_id":"([^"]+)".*/\1/')
fi

if [ -n "$rust_token" ]; then
	range_output=$("$engine" exec "$RUST_CONTAINER" wget -q -S -O - \
		--header "Cookie: learnvault_session=$rust_token" \
		--header "Range: bytes=0-15" \
		"http://127.0.0.1:$RUST_PORT/api/media?path=$LESSON_PATH" 2>&1 || true)
	if printf '%s' "$range_output" | grep -q ' 206'; then
		pass 'authenticated range media request returns 206'
	else
		fail 'authenticated range media request did not return 206'
	fi
else
	skip 'range media request skipped: no Rust session'
fi

if [ -n "$rust_token" ] && [ -n "$rust_media_id" ]; then
	"$engine" exec "$RUST_CONTAINER" wget -q -O - \
		--header "Cookie: learnvault_session=$rust_token" \
		--header "Origin: http://127.0.0.1:$RUST_PORT" \
		--header "Content-Type: application/json" \
		--post-data "{\"media_id\":\"$rust_media_id\",\"position_seconds\":42}" \
		"http://127.0.0.1:$RUST_PORT/api/study/position" >"$workdir/rust-study.json" 2>/dev/null || true
	if grep -q '"position_seconds":42' "$workdir/rust-study.json" && grep -q '"recorded":true' "$workdir/rust-study.json"; then
		pass 'study position is recorded on the imported media'
	else
		fail "study position was not recorded: $(cat "$workdir/rust-study.json" 2>/dev/null)"
	fi
else
	skip 'study write skipped: no Rust session or no imported media id'
fi

container_uid=$("$engine" exec "$RUST_CONTAINER" id -u 2>/dev/null || true)
if [ "$container_uid" = 10001 ]; then
	pass 'Rust server runs as the non-root user (uid 10001)'
else
	fail "Rust server is not running as uid 10001 (got: ${container_uid:-<unknown>})"
fi

if "$engine" exec "$RUST_CONTAINER" sh -c 'grep -Eq "^NoNewPrivs:[[:space:]]*1$" /proc/self/status && grep -Eq "^(CapEff|CapBnd):[[:space:]]*0+$" /proc/self/status' >/dev/null 2>&1; then
	pass 'no-new-privileges is set and all capabilities are dropped'
else
	fail 'no-new-privileges or capability dropping is not in effect'
fi

if "$engine" exec "$RUST_CONTAINER" test -r "/library/$LESSON_PATH"; then
	pass 'mounted synthetic library content is readable'
else
	fail 'mounted synthetic library content is not readable'
fi

if "$engine" exec "$RUST_CONTAINER" cat /proc/mounts 2>/dev/null \
	| grep -Eq ' /library .*[[:space:]]ro(,|$)'; then
	pass 'library is mounted read-only'
else
	fail 'library is not mounted read-only'
fi

if "$engine" exec "$RUST_CONTAINER" sh -c 'touch /library/.write-probe' >/dev/null 2>&1; then
	fail 'writing to /library succeeded unexpectedly'
else
	pass 'container cannot write to the read-only library'
fi

if "$engine" exec "$RUST_CONTAINER" sh -c 'touch /app/.write-probe' >/dev/null 2>&1; then
	fail 'writing to the container root filesystem succeeded unexpectedly'
else
	pass 'container root filesystem is read-only'
fi

printf '\nRestart check:\n'
db_before=$("$engine" exec "$RUST_CONTAINER" stat -c '%d:%i' /data/learnvault.sqlite 2>/dev/null || true)
"$engine" exec "$RUST_CONTAINER" sh -c 'printf marker > /data/restart-probe' >/dev/null 2>&1 || true
"$engine" restart "$RUST_CONTAINER" >/dev/null

restart_ok=0
restart_wait=0
while [ "$restart_wait" -lt 30 ]; do
	if "$engine" exec "$RUST_CONTAINER" wget -q -O /dev/null \
		"http://127.0.0.1:$RUST_PORT/api/healthz" >/dev/null 2>&1; then
		restart_ok=1
		break
	fi
	restart_wait=$((restart_wait + 1))
	sleep 1
done
if [ "$restart_ok" = 1 ]; then
	pass 'Rust server serves /api/healthz again after a restart'
else
	fail 'Rust server did not recover after a restart'
	"$engine" logs "$RUST_CONTAINER" 2>&1 | tail -n 20 || true
fi

db_after=$("$engine" exec "$RUST_CONTAINER" stat -c '%d:%i' /data/learnvault.sqlite 2>/dev/null || true)
if [ -n "$db_before" ] && [ "$db_before" = "$db_after" ]; then
	pass 'imported Rust database survives a restart (same inode)'
else
	fail "imported Rust database identity changed across a restart ($db_before -> $db_after)"
fi

if [ -n "$rust_token" ] && [ -n "$rust_media_id" ]; then
	"$engine" exec "$RUST_CONTAINER" wget -q -O - \
		--header "Cookie: learnvault_session=$rust_token" \
		"http://127.0.0.1:$RUST_PORT/api/study/progress?media_id=$rust_media_id" >"$workdir/rust-progress.json" 2>/dev/null || true
	if grep -q '"position_seconds":42' "$workdir/rust-progress.json" && grep -q '"recorded":true' "$workdir/rust-progress.json"; then
		pass 'study progress persists across a restart'
	else
		fail "study progress did not persist across restart: $(cat "$workdir/rust-progress.json" 2>/dev/null)"
	fi
else
	skip 'study restart check skipped: no Rust session or no imported media id'
fi

# Cleanup is also enforced by the EXIT trap; removing it here lets the script assert that
# no container is left behind.
"$engine" rm -f "$RUST_CONTAINER" >/dev/null 2>&1 || true
rust_started=0
if "$engine" ps -a --format '{{.Names}}' 2>/dev/null | grep -qx "$RUST_CONTAINER"; then
	fail 'rehearsal container was not removed'
else
	pass 'rehearsal container was removed by cleanup'
fi

printf '\nSummary:\n'
if [ "$failures" -eq 0 ]; then
	printf 'PASS: synthetic Go->Rust cutover rehearsal completed. This is not a production cutover.\n'
else
	printf 'FAIL: %s check(s) failed.\n' "$failures" >&2
	exit 1
fi
